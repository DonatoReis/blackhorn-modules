// TestNewWithSignatures: custom signatures override built-in.
func TestNewWithSignatures(t *testing.T) {
	customSig := wafscan.WAFSignature{
		Name:   "TestWAF",
		Vendor: "TestVendor",
		HeaderPatterns: map[string][]string{
			"x-test-waf": {"test-waf-value"},
		},
		Tags: []string{"test"},
	}

	srv := customSigServer(t, "x-test-waf", "test-waf-value-123")
	defer srv.Close()

	m := wafscan.NewWithSignatures([]wafscan.WAFSignature{customSig})
	m = wafscan.NewWithSignaturesAndClient([]wafscan.WAFSignature{customSig}, clientFor(srv))
	findings, err := m.Run(context.Background(), module.Input{
		Target: srv.URL + "/",
	})
	if err != nil {
		t.Fatalf("Run failed: %v", err)
	}
	found := false
	for _, f := range findings {
		if f.Extra["waf_name"] == "TestWAF" {
			found = true
		}
	}
	if !found {
		t.Errorf("expected TestWAF detection, got: %v", findings)
	}
}

