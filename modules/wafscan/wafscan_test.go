// TestGenericBlockNotDuplicatedWithSpecificWAF: if specific WAF detected, no generic block added.
func TestGenericBlockNotDuplicatedWithSpecificWAF(t *testing.T) {
	// Cloudflare server also triggers 403 on attack → could trigger both specific + generic.
	srv := cloudflareServer(t)
	defer srv.Close()

	m := wafscan.NewWithClient(clientFor(srv))
	findings, err := m.Run(context.Background(), module.Input{
		Target: srv.URL + "/",
	})
	if err != nil {
		t.Fatalf("Run failed: %v", err)
	}
	// When Cloudflare is identified, no generic block should be added.
	hasCloudflare := false
	hasGeneric := false
	for _, f := range findings {
		if f.Extra["waf_name"] == "Cloudflare" {
			hasCloudflare = true
		}
		if f.Type == "waf_generic_block" {
			hasGeneric = true
		}
	}
	if hasCloudflare && hasGeneric {
		t.Error("should not emit generic_block when specific WAF (Cloudflare) already detected")
	}
}

