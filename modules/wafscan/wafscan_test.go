// isAttackProbe checks if a request is the WAF attack probe (any suspicious query param).
func isAttackProbe(r *http.Request) bool {
	raw := r.URL.RawQuery
	return strings.Contains(raw, "id=") && strings.Contains(raw, "OR") ||
		strings.Contains(raw, "script") || strings.Contains(raw, "etc") ||
		strings.Contains(raw, "1%27") || strings.Contains(raw, "%27")
}

// cloudflareServer simulates a Cloudflare-protected origin.
func cloudflareServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("server", "cloudflare")
		w.Header().Set("cf-ray", "7abc123456789-GRU")
		if isAttackProbe(r) {
			w.WriteHeader(403)
			w.Write([]byte(`cloudflare ray id: 7abc123456789-GRU attention required! | cloudflare`))
			return
		}
		w.WriteHeader(200)
		w.Write([]byte(`{"status":"ok"}`))
	}))
}

// modsecurityServer simulates a ModSecurity-blocked response.
func modsecurityServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if isAttackProbe(r) {
			w.Header().Set("server", "Apache/2.4 mod_security")
			w.WriteHeader(406)
			w.Write([]byte(`Not Acceptable. This error was generated by mod_security`))
			return
		}
		w.WriteHeader(200)
		w.Write([]byte(`OK`))
	}))
}

// incapsulaServer simulates an Imperva/Incapsula WAF.
func incapsulaServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("x-iinfo", "11-123456-0 NNNN CT(52,0,0,0) RT(1638000000000,0) q(0,0,0,-1) r(0,-1) U5")
		http.SetCookie(w, &http.Cookie{Name: "incap_ses_123_456", Value: "testvalue"})
		w.WriteHeader(403)
		w.Write([]byte(`incapsula incident id: 1234567890`))
	}))
}

