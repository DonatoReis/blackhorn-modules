// genericBlockServer: returns 200 for clean, 403 for attack.
func genericBlockServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if isAttackProbe(r) {
			w.WriteHeader(403)
			w.Write([]byte(`Forbidden`))
			return
		}
		w.WriteHeader(200)
		w.Write([]byte(`OK`))
	}))
}

// noWAFServer: always returns 200 for any request.
func noWAFServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(200)
		w.Write([]byte(`<html><body>Welcome</body></html>`))
	}))
}

// customSigServer: returns specific header for custom signature testing.
func customSigServer(t *testing.T, headerKey, headerValue string) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set(headerKey, headerValue)
		w.WriteHeader(200)
		w.Write([]byte(`OK`))
	}))
}

func clientFor(srv *httptest.Server) *http.Client { return srv.Client() }

